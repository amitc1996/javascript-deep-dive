const questions = [
    {
        question:
            "Who created JavaScript?",
        answer:
            "Brendan Eich"
    },
    {
        question:
            "When was JavaScript created?",
        answer:
            "1995"
    },
    {
        question:
            "What standard defines JavaScript?",
        answer:
            "ECMAScript"
    }
];

questions.forEach(
    ({ question, answer }, index) => {

        console.log(
            `${index + 1}. ${question}`
        );

        console.log(
            `Answer: ${answer}`
        );
    }
);

